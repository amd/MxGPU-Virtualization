/**
 * Information captured for each error from a SR-IOV GPU device
 *
 * @timestamp: Time stamp (in nanoseconds) when the error happened
 * @log_code: unique error code that describes the type of error. This
 *  numeric code can be used as an index into a string table to obtain
 *  a human readable description of the error. The high 4 bits indicates the
 *  error category, such as GIM, PF, VF, VBIOS, etc. The low 12 bits indicates
 * the error index in the sub-category error text list.
 * @log_level: indicates the severity of the error
 * @vf_idx: PF or VF function_index
 * @log_data: Data value associated with the specific error.
 * @log_location: Code address where the error was originally captured.
 */
struct amdgv_log_entry {
	uint64_t timestamp;
	uint32_t log_code;
	uint8_t  log_level;
	uint32_t log_flags;
	uint32_t vf_idx;
	uint64_t log_data;
	uint64_t log_location;
	uint64_t log_data_ext[AMDGV_LOG_EXT_MAX_ARGS];
};

