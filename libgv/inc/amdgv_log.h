/****************************************************
 * Macro for future extension
 *
 * Current error code is defined in the following:
 * unsigned 32 bits integer
 * bit [0  - 11] are subcode
 * bit [12 - 17] are category
 * bit [18 - 30] are reserved
 * bit [31]      is always 1
 *
 * Current error mask is defined in the following:
 * unsigned 64 bits integer
 * bit [0  -  59] are category mask
 * bit [60  - 63] are severity  level
 *
 ****************************************************/
/* subcode bit length, increase this one if necessary */
#define AMDGV_LOG_SUBCODE_LENGTH  (12)

/* category bit length, should no more than 60 categories, but need 6 bits to hold */
#define AMDGV_LOG_CATEGORY_LENGTH (6)

/* mask category bit length, this is the upper limit of category count */
#define AMDGV_LOG_MASK_CATEGORY_LENGTH (60)

/* mask severity bit length */
#define AMDGV_LOG_MASK_SEVERITY_LENGTH (4)

/* The length of error text should be less than this number. */
#define AMDGV_LOG_MSG_SIZE    (256)

/* The safe length of printing out the full error message to buffer. */
#define AMDGV_LOG_BUF_SAFE_SIZE (AMDGV_LOG_MSG_SIZE + 120)

/* error entry flags */
#define AMDGV_LOG_FLAG_EXT 1

#define AMDGV_LOG_EXT_MAX_ARGS 15

/****************************************************
 * Helper Macro
 ****************************************************/
#define AMDGV_LOG_SUBCODE_MASK   ((1 << AMDGV_LOG_SUBCODE_LENGTH) - 1)
#define AMDGV_LOG_CATEGORY_MASK  ((1 << AMDGV_LOG_CATEGORY_LENGTH) - 1)
#define AMDGV_LOG_CATEGORY_SHIFT AMDGV_LOG_SUBCODE_LENGTH

#define AMDGV_LOG_MASK_SEVERITY_MASK  ((1UL << AMDGV_LOG_MASK_SEVERITY_LENGTH) - 1)
#define AMDGV_LOG_MASK_SEVERITY_SHIFT AMDGV_LOG_MASK_CATEGORY_LENGTH
#define AMDGV_LOG_MASK_CATEGORY_MASK  ((1ULL << AMDGV_LOG_MASK_CATEGORY_LENGTH) - 1)

/* error code MSB should be set to 1 */
#define AMDGV_LOG_CODE(cate, sub) \
	((1<<31) | \
	(((cate) & AMDGV_LOG_CATEGORY_MASK) << AMDGV_LOG_CATEGORY_SHIFT) | \
	((sub) & AMDGV_LOG_SUBCODE_MASK))

#define AMDGV_LOG_CATEGORY(code)     (((code) >> AMDGV_LOG_CATEGORY_SHIFT) & AMDGV_LOG_CATEGORY_MASK)
#define AMDGV_LOG_SUBCODE(code)      ((code) & AMDGV_LOG_SUBCODE_MASK)

#define AMDGV_LOG_MASK_CATEGORY(mask)     ((mask) & AMDGV_LOG_MASK_CATEGORY_MASK)
#define AMDGV_LOG_MASK_SEVERITY(mask)     (((mask) >> AMDGV_LOG_MASK_SEVERITY_SHIFT) & AMDGV_LOG_MASK_SEVERITY_MASK)

#define AMDGV_LOG_DATA_32_32(a, b)  ((((uint64_t)a) << 32) | (((uint64_t)b) & 0xFFFFFFFF))
#define AMDGV_LOG_DATA_16_16_32(a, b, c) ((((uint64_t)a) << 48) | (((uint64_t)b) << 32) | (((uint64_t)c) & 0xFFFFFFFF))
#define AMDGV_LOG_DATA_16_16_16_16(a, b, c, d) ((((uint64_t)a) << 48) | (((uint64_t)b) << 32) |  (((uint64_t)c) << 16) | (((uint64_t)d) & 0xFFFFFFFF))

#define AMDGV_LOG_SYS_MSG_SIZE 512

/****************************************************
 * Function Define and Macro
 ****************************************************/
#define amdgv_put_log(idx_vf, code, data) \
	amdgv_put_event(adapt, idx_vf, code, data, __func__, __LINE__)

#define amdgv_put_log_ext(idx_vf, code, data, ...) \
	amdgv_put_event_ext(adapt, idx_vf, code, data, __func__, __LINE__, __VA_ARGS__)

#define AMDGV_LOG_PRINT_HEADER "%s[%x:%x:%x:%x][%s][%s:%d] "

/*
* define error severity
* ERROR_HIGH : critical error, requires RMA, flash VBIOS or reboot host
* ERROR_MED : important error requires reload GIM, reset whole GPU or VF_FLR
* ERROR_LOW : less significant error requires reboot guest or log only
*        as the action will be performed by driver itself
* WARNING : incorrect event happened but no action is required
* INFO : just notification of occurred event
*/
enum AMDGV_LOG_SEVERITY {
	AMDGV_LOG_SEVERITY_ERROR_HIGH,
	AMDGV_LOG_SEVERITY_ERROR_MED,
	AMDGV_LOG_SEVERITY_ERROR_LOW,
	AMDGV_LOG_SEVERITY_WARNING,
	AMDGV_LOG_SEVERITY_INFO,
	AMDGV_LOG_SEVERITY_DEBUG,
};

